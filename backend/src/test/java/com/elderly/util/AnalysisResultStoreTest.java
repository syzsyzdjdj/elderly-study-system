package com.elderly.util;

import com.baomidou.mybatisplus.core.conditions.Wrapper;
import com.elderly.config.SparkConfig;
import com.elderly.entity.AnalysisStudyTrend;
import com.elderly.entity.AnalysisTextClassify;
import com.elderly.mapper.*;
import org.junit.jupiter.api.*;
import org.junit.jupiter.api.extension.ExtendWith;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.*;
import org.springframework.test.context.ContextConfiguration;
import org.springframework.test.context.junit.jupiter.SpringExtension;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import javax.sql.DataSource;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;
import static org.mockito.ArgumentMatchers.any;

@ExtendWith(SpringExtension.class)
@ContextConfiguration(classes = AnalysisResultStoreTest.Config.class)
class AnalysisResultStoreTest {
    @Autowired AnalysisResultStore store;
    @Autowired JdbcTemplate jdbc;
    @Autowired AnalysisStudyTrendMapper trends;
    @Autowired AnalysisTextClassifyMapper texts;
    @BeforeEach void init() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS saved_trend(study_date DATE PRIMARY KEY, minutes BIGINT)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS analysis_model_metric(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,task VARCHAR(40),run_id VARCHAR(64),data_scope VARCHAR(16),metric VARCHAR(64),value DOUBLE,samples BIGINT,status VARCHAR(24),detail VARCHAR(1000))");
        jdbc.update("DELETE FROM saved_trend"); jdbc.update("DELETE FROM analysis_model_metric");
        jdbc.update("INSERT INTO saved_trend VALUES('2026-10-01', 99)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS saved_text(category VARCHAR(64),average DOUBLE,minimum DOUBLE,high BIGINT)");
        jdbc.update("DELETE FROM saved_text");
        jdbc.execute("CREATE TABLE IF NOT EXISTS analysis_question_prediction(question_id BIGINT PRIMARY KEY,question_hash VARCHAR(64),category VARCHAR(64),confidence DOUBLE,run_id VARCHAR(64),data_scope VARCHAR(16))");
        jdbc.update("DELETE FROM analysis_question_prediction");
        clearInvocations(trends);
    }
    @Test void failedInsertRollsBackDeleteAndPreviouslyInsertedRows() {
        Map<String, String> row = row("2026-10-02");
        assertThrows(RuntimeException.class, () -> store.save("study_trend", Map.of("study_trend", List.of(row, row)), "batch"));
        assertEquals(99L, jdbc.queryForObject("SELECT minutes FROM saved_trend WHERE study_date='2026-10-01'", Long.class));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM saved_trend", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM analysis_model_metric", Integer.class));
    }
    @Test void malformedRowsAreRejectedBeforeDeletingResults() {
        Map<String, String> malformed = row("not-a-date");
        assertThrows(RuntimeException.class, () -> store.save("study_trend", Map.of("study_trend", List.of(malformed)), "batch"));
        verify(trends, never()).delete(any(Wrapper.class));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM saved_trend", Integer.class));
    }
    @Test void emptyValidResultStillRecordsSuccessfulRunAndScope() {
        store.save("study_trend", Map.of("study_trend", List.of()), "same-snapshot");
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM saved_trend", Integer.class));
        assertEquals("same-snapshot", jdbc.queryForObject("SELECT run_id FROM analysis_model_metric", String.class));
        assertEquals("real", jdbc.queryForObject("SELECT data_scope FROM analysis_model_metric", String.class));
    }
    @Test void identifiersRemainExactAndMissingValuesAreNotSilentlyZeroed() {
        assertEquals(9007199254740993L, AnalysisResultStore.integer(Map.of("id", "9007199254740993"), "id"));
        assertThrows(IllegalArgumentException.class, () -> AnalysisResultStore.integer(Map.of(), "id"));
        assertThrows(ArithmeticException.class, () -> AnalysisResultStore.integer(Map.of("id", "1.5"), "id"));
        assertThrows(IllegalArgumentException.class, () -> AnalysisResultStore.number(Map.of("score", "NaN"), "score"));
    }

    @Test void confidenceIsPersistedAndUndeterminedResultsKeepNullProbabilities() {
        Map<String, String> accepted = classification("支付", "0.9", "0.85", "2");
        Map<String, String> unknown = classification("未确定业务", "", "", "0");
        store.save("text_classify", classificationOutput(List.of(accepted, unknown)), "classification-batch");
        assertEquals(0.9, jdbc.queryForObject("SELECT average FROM saved_text WHERE category='支付'", Double.class));
        assertNull(jdbc.queryForObject("SELECT average FROM saved_text WHERE category='未确定业务'", Double.class));
        assertEquals(2L, jdbc.queryForObject("SELECT high FROM saved_text WHERE category='支付'", Long.class));
        assertThrows(IllegalArgumentException.class, () -> store.save("text_classify",
                classificationOutput(List.of(classification("支付", "1.1", "0.9", "1"))), "bad"));
        assertThrows(IllegalArgumentException.class, () -> store.save("text_classify",
                classificationOutput(List.of(classification("未确定业务", "0.99", "0.99", "0"))), "bad"));
        assertThrows(IllegalArgumentException.class, () -> store.save("text_classify",
                classificationOutput(List.of(classification("支付", "0.9", "0.9", "3"))), "bad"));
        assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM saved_text", Integer.class));
        assertEquals("classification-batch", jdbc.queryForObject("SELECT DISTINCT run_id FROM analysis_model_metric", String.class));
    }

    @Test void legacyYarnQuotedEmptyMetricsDoNotRollBackSuccessfulRecommendations() throws Exception {
        java.nio.file.Path file = java.nio.file.Files.createTempFile("legacy-yarn-metrics-", ".tsv");
        try {
            java.nio.file.Files.writeString(file, "metric\tvalue\tsamples\tstatus\tdetail\n"
                    + "recall_at_5\t\"\"\t2\tinsufficient_data\t至少需要3名用户和5个正样本\n");
            List<Map<String,String>> metrics = TsvResultParser.parseFile(file);
            for (String task : List.of("item_cf", "als_recommend")) {
                store.save(task, Map.of(task, List.of(), task+"_metrics", metrics), "recovered-batch");
                assertNull(jdbc.queryForObject("SELECT value FROM analysis_model_metric WHERE task=? AND metric='recall_at_5'", Double.class, task));
                assertEquals("insufficient_data", jdbc.queryForObject("SELECT status FROM analysis_model_metric WHERE task=? AND metric='recall_at_5'", String.class, task));
                assertEquals(2L, jdbc.queryForObject("SELECT samples FROM analysis_model_metric WHERE task=? AND metric='recall_at_5'", Long.class, task));
            }
        } finally { java.nio.file.Files.deleteIfExists(file); }
    }

    @Test void legacyYarnQuotedEmptyConfidenceRemainsNullWithoutStrippingTextQuotes() {
        Map<String,String> unknown = new HashMap<>(classification("未确定业务", "\"\"", "\"\"", "0"));
        store.save("text_classify", classificationOutput(List.of(unknown)), "legacy-classification");
        assertNull(jdbc.queryForObject("SELECT average FROM saved_text", Double.class));
        assertNull(jdbc.queryForObject("SELECT minimum FROM saved_text", Double.class));
        assertEquals("\"医保\"", AnalysisResultStore.text(Map.of("title", "\"医保\""), "title"));
        assertThrows(IllegalArgumentException.class, () -> AnalysisResultStore.number(Map.of("score", "\"\""), "score"));
        assertThrows(IllegalArgumentException.class, () -> AnalysisResultStore.number(Map.of("score", "\"0.5\""), "score"));
    }

    @Test void predictionsAreSavedWithBatchAndBadDetailsRollBackPreviousResults() {
        Map<String,List<Map<String,String>>> raw = new HashMap<>(classificationOutput(List.of(classification("支付","0.9","0.9","2"))));
        String hash = String.join("", Collections.nCopies(64,"a"));
        raw.put("text_classify_detail",List.of(
                Map.of("question_id","1","question_hash",hash,"category","支付","confidence","0.9"),
                Map.of("question_id","2","question_hash",hash,"category","支付","confidence","0.9")));
        store.save("text_classify",raw,"prediction-batch");
        assertEquals(2,jdbc.queryForObject("SELECT COUNT(*) FROM analysis_question_prediction",Integer.class));
        assertEquals("prediction-batch",jdbc.queryForObject("SELECT run_id FROM analysis_question_prediction WHERE question_id=1",String.class));
        raw.put("text_classify_detail",List.of());
        assertThrows(IllegalArgumentException.class,()->store.save("text_classify",raw,"bad-batch"));
        assertEquals(2,jdbc.queryForObject("SELECT COUNT(*) FROM analysis_question_prediction",Integer.class));
        assertEquals("prediction-batch",jdbc.queryForObject("SELECT DISTINCT run_id FROM analysis_question_prediction",String.class));
    }

    private static Map<String, String> classification(String category, String average, String minimum, String high) {
        return Map.of("province", "四川", "category", category, "question_count", "2",
                "avg_confidence", average, "min_confidence", minimum, "high_confidence_count", high);
    }
    private static Map<String, List<Map<String, String>>> classificationOutput(List<Map<String, String>> rows) {
        return Map.of("text_classify", rows, "text_classify_metrics", List.of(Map.of(
                "metric", "accuracy", "value", "", "samples", "0", "status", "unvalidated", "detail", "没有人工标签")));
    }
    private static Map<String, String> row(String date) {
        return Map.of("study_date", date, "study_count", "3", "study_duration_min", "5");
    }
    @Configuration @EnableTransactionManagement(proxyTargetClass = true)
    static class Config {
        @Bean DataSource dataSource() { return new DriverManagerDataSource("jdbc:h2:mem:analysis-store;DB_CLOSE_DELAY=-1;NON_KEYWORDS=VALUE", "sa", ""); }
        @Bean JdbcTemplate jdbc(DataSource ds) { return new JdbcTemplate(ds); }
        @Bean PlatformTransactionManager tx(DataSource ds) { return new DataSourceTransactionManager(ds); }
        @Bean AnalysisStudyTrendMapper trends(JdbcTemplate jdbc) {
            AnalysisStudyTrendMapper mapper = mock(AnalysisStudyTrendMapper.class);
            doAnswer(a -> jdbc.update("DELETE FROM saved_trend")).when(mapper).delete(any(Wrapper.class));
            when(mapper.insert(any(AnalysisStudyTrend.class))).thenAnswer(a -> {
                AnalysisStudyTrend value = a.getArgument(0);
                return jdbc.update("INSERT INTO saved_trend VALUES(?,?)", value.getStudyDate(), value.getStudyDurationMin());
            });
            return mapper;
        }
        @Bean AnalysisTextClassifyMapper texts(JdbcTemplate jdbc) {
            AnalysisTextClassifyMapper mapper = mock(AnalysisTextClassifyMapper.class);
            doAnswer(a -> jdbc.update("DELETE FROM saved_text")).when(mapper).delete(any(Wrapper.class));
            when(mapper.insert(any(AnalysisTextClassify.class))).thenAnswer(a -> {
                AnalysisTextClassify value = a.getArgument(0);
                return jdbc.update("INSERT INTO saved_text VALUES(?,?,?,?)", value.getCategory(), value.getAvgConfidence(),
                        value.getMinConfidence(), value.getHighConfidenceCount());
            });
            return mapper;
        }
        @Bean AnalysisResultStore store(AnalysisStudyTrendMapper trends, AnalysisTextClassifyMapper texts, JdbcTemplate jdbc) {
            return new AnalysisResultStore(mock(AnalysisResultMapper.class), mock(AnalysisCourseHotMapper.class),
                    mock(AnalysisCategoryShareMapper.class), trends, mock(AnalysisAssociationRuleMapper.class),
                    mock(AnalysisWordFreqMapper.class), mock(AnalysisRecommendMapper.class), mock(AnalysisRecommendAlsMapper.class),
                    texts, mock(CourseInfoMapper.class), jdbc, new SparkConfig());
        }
    }
}
